const TABLES: Record<string, Table> = { en, ru, it };

// Steam's own name for the interface language (LocalizationManager) -> the table above.
const STEAM_LANG: Record<string, string> = { russian: "ru", italian: "it", english: "en" };

export const lang = (() => {
  const raw = String((window as any).LocalizationManager?.m_rgLocalesToUse?.[0] ?? navigator.language ?? "en").toLowerCase();
  return STEAM_LANG[raw] ?? (TABLES[raw.slice(0, 2)] ? raw.slice(0, 2) : "en");
})();

export const t = (key: string): string => TABLES[lang]?.[key] ?? en[key] ?? key;
