#!/bin/bash
# Copies luchd's presenter page (luchd/src/present.html, present.js) into the Mac app as Swift strings, so both
# senders serve the very same page. PresentPageTests fails when the copy is behind; run this, then build.
# SPDX-License-Identifier: GPL-3.0-or-later
set -euo pipefail
cd "$(dirname "$0")/.."
SRC=../luchd/src
OUT=Sources/LuchPresent/PresentPage.swift
for f in present.html present.js; do
    if grep -q '"""#' "$SRC/$f"; then echo "$f holds \"\"\"#: pick another delimiter" >&2; exit 1; fi
done
{
    echo '// Generated by Tools/sync-present.sh from luchd/src/present.html and present.js: do not edit here.'
    echo '// SPDX-License-Identifier: GPL-3.0-or-later'
    echo
    echo 'enum PresentPage {'
    echo '    static let html = #"""'
    cat "$SRC/present.html"
    echo '"""#'
    echo
    echo '    static let script = #"""'
    cat "$SRC/present.js"
    echo '"""#'
    echo '}'
} > "$OUT"
echo "wrote $OUT"
